#!/usr/bin/env python3
"""Two readings of the evidence map, after the human review of the criteria
(docs/assessment/human-review-accuracy.md).

- literal (the evidence map as it is): Claude's reading of the provisions'
  wording; criteria judged "not evidence" or "cannot be decided" stay out or
  stay candidates.
- strict: the reviewer's reading; the criteria the reviewer judged as
  evidence where Claude did not are counted (T5, S3, S4, S6, S8, S14, O2-O6).
  A3 and O1 were agreed as not evidence and stay out.

usage: readings.py EVIDENCE_MAP OUT_STRICT_MAP
"""
import json
import sys

WEAK_TLS = "risk_kind=deprecated_tls_version|risk_kind=(rc4|3des|des|null|export|anonymous|md5)_cipher"


def strict(m):
    for p in m["provisions"]:
        v = p["provision"]
        if v in ("5.1-3", "5.5-1"):                      # T5: CBC suites count
            p["require_pattern"] = p.get("require_pattern", WEAK_TLS) + "|risk_kind=cbc_cipher"
        if v in ("5.5-6", "5.5-7"):                      # S3, S4, S6, S8: no exclusions
            p.pop("exclude_pattern", None)
        if v == "5.5-6" and "I1_CREDENTIAL_GUESSING_OBSERVED" not in p["signals"]:
            p["signals"].append("I1_CREDENTIAL_GUESSING_OBSERVED")  # S14: attackers' guesses
        if v == "5.9-3":                                 # O2, O3: any repeated connection
            p.pop("require_pattern", None)
        if v in ("5.1-5", "5.12-1", "5.3-7", "5.9-3"):   # O3-O6: candidates count as violations
            p["status"] = "implemented"
        p["reading"] = "strict"
    m["description"] = "GENERATED by scripts/assessment/readings.py from evidence-map.json: the reviewer's strict reading. " + m["description"]
    return m


def main():
    src, out = sys.argv[1:3]
    m = json.load(open(src))
    json.dump(strict(m), open(out, "w"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
