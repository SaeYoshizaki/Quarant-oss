#!/usr/bin/env python3
"""Build knowledge/component_cves.json: the CVEs of software components that
devices name in their traffic (HTTP Server, SSH banners, DHCP vendor class),
with the affected version ranges, from the NVD API 2.0, and whether CISA
lists the CVE as known exploited (KEV).

Only public data is downloaded; nothing about the captures is sent. The
matching itself runs locally (internal/versionvuln).

usage: fetch_component_cves.py OUT_JSON
"""
import json
import sys
import time
import urllib.request

# Zeek's software name (lower case) -> NVD CPE vendor:product. udhcp sends
# "udhcp <BusyBox version>" since it became part of BusyBox (1.x); the
# stand-alone udhcp 0.9.x is a different project and is not matched.
# "suite": the product bundles many programs (BusyBox applets), so a CVE may
# concern one that the device does not build in.
PRODUCTS = [
    {"names": ["dropbear"], "cpe": "dropbear_ssh_project:dropbear_ssh"},
    {"names": ["openssh"], "cpe": "openbsd:openssh"},
    {"names": ["lighttpd"], "cpe": "lighttpd:lighttpd"},
    {"names": ["udhcp", "busybox"], "cpe": "busybox:busybox", "min_version": "1.0", "suite": True},
    {"names": ["gsoap"], "cpe": "genivia:gsoap"},
    {"names": ["dhcpcd"], "cpe": "roy_marples:dhcpcd"},
]
NVD = "https://services.nvd.nist.gov/rest/json/cves/2.0?virtualMatchString=cpe:2.3:a:{cpe}&resultsPerPage=2000&startIndex={start}"
KEV = "https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "quarant-knowledge-fetch"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)


def severity(cve):
    m = cve.get("metrics", {})
    for key in ("cvssMetricV31", "cvssMetricV30", "cvssMetricV2"):
        for x in m.get(key, []):
            if x.get("type") == "Primary" or len(m[key]) == 1:
                d = x["cvssData"]
                return d.get("baseSeverity") or x.get("baseSeverity"), d.get("baseScore")
    return None, None


def ranges(cve, cpe):
    out = []
    prefix = "cpe:2.3:a:" + cpe + ":"
    for conf in cve.get("configurations", []):
        for node in conf.get("nodes", []):
            for m in node.get("cpeMatch", []):
                if not m.get("vulnerable") or not m["criteria"].startswith(prefix):
                    continue
                r = {}
                ver = m["criteria"].split(":")[5]
                if ver not in ("*", "-"):
                    r["exact"] = ver
                for k in ("versionStartIncluding", "versionStartExcluding", "versionEndIncluding", "versionEndExcluding"):
                    if k in m:
                        r[k] = m[k]
                if r and r not in out:
                    out.append(r)
    return out


def main():
    kev = {v["cveID"] for v in get(KEV)["vulnerabilities"]}
    products = []
    for p in PRODUCTS:
        cves, start, total = [], 0, None
        while total is None or start < total:
            time.sleep(6)  # NVD allows 5 requests per 30 s without a key
            d = get(NVD.format(cpe=p["cpe"], start=start))
            total = d["totalResults"]
            for v in d["vulnerabilities"]:
                c = v["cve"]
                rs = ranges(c, p["cpe"])
                if not rs:
                    continue
                sev, score = severity(c)
                cves.append({"id": c["id"], "published": c["published"][:10], "severity": sev, "score": score,
                             "kev": c["id"] in kev, "ranges": rs})
            start += d["resultsPerPage"]
        entry = dict(p)
        entry["cves"] = sorted(cves, key=lambda x: x["id"])
        products.append(entry)
        print(p["cpe"], len(entry["cves"]), file=sys.stderr)
    out = {"description": "CVEs of components named in device traffic, with affected version ranges (NVD API 2.0) and CISA KEV membership. Generated by scripts/knowledge/fetch_component_cves.py.",
           "fetched": time.strftime("%Y-%m-%d"), "products": products}
    with open(sys.argv[1], "w") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")


if __name__ == "__main__":
    main()
